-- ---------------------------------------------------------------------
-- usuarios: credenciales y datos personales
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS usuarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(255) NOT NULL,
    apellido       VARCHAR(255) NOT NULL,
    telefono       VARCHAR(255) NOT NULL,
    identificacion VARCHAR(20)  NOT NULL,
    correo         VARCHAR(255) NOT NULL,
    contrasena     VARCHAR(255) NOT NULL,
    activo         BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_usuarios_identificacion UNIQUE (identificacion),
    CONSTRAINT uk_usuarios_correo         UNIQUE (correo)
);

-- ---------------------------------------------------------------------
-- roles_usuario: roles múltiples por usuario (@ElementCollection)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS roles_usuario (
    usuario_id BIGINT      NOT NULL,
    rol        VARCHAR(20) NOT NULL,
    CONSTRAINT fk_roles_usuario_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT uk_roles_usuario UNIQUE (usuario_id, rol),
    CONSTRAINT ck_roles_usuario_rol
        CHECK (rol IN ('AGRICULTOR', 'COMPRADOR', 'TRANSPORTISTA'))
);

-- ---------------------------------------------------------------------
-- agricultores: perfil de agricultor (1:1 con usuarios)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS agricultores (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipio  VARCHAR(255) NOT NULL,
    usuario_id BIGINT       NOT NULL,
    CONSTRAINT uk_agricultores_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_agricultores_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id)
);

-- ---------------------------------------------------------------------
-- compradores: perfil de comprador (1:1 con usuarios)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS compradores (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipio         VARCHAR(255) NOT NULL,
    direccion_entrega VARCHAR(255) NOT NULL,
    latitud           NUMERIC(9, 6),
    longitud          NUMERIC(9, 6),
    usuario_id        BIGINT       NOT NULL,
    CONSTRAINT uk_compradores_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_compradores_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id)
);

-- ---------------------------------------------------------------------
-- productos: productos agrícolas publicados
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS productos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(255)   NOT NULL,
    categoria      VARCHAR(255)   NOT NULL,
    cantidad       INTEGER        NOT NULL,
    unidad_medida  VARCHAR(255)   NOT NULL,
    precio         NUMERIC(38, 2) NOT NULL,
    fecha_cosecha  DATE           NOT NULL,
    agricultor_id  BIGINT         NOT NULL,
    CONSTRAINT fk_productos_agricultor FOREIGN KEY (agricultor_id)
        REFERENCES agricultores (id),
    CONSTRAINT ck_productos_unidad_medida CHECK (unidad_medida IN (
        'KILOGRAMO', 'GRAMO', 'TONELADA', 'LIBRA', 'ARROBA', 'UNIDAD',
        'DOCENA', 'BULTO', 'SACO', 'CANASTILLA', 'CAJA', 'ATADO'))
);

-- ---------------------------------------------------------------------
-- contactos: solicitudes de un comprador sobre un producto
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS contactos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comprador_id    BIGINT        NOT NULL,
    producto_id     BIGINT        NOT NULL,
    mensaje         VARCHAR(1000) NOT NULL,
    fecha_envio     TIMESTAMP     NOT NULL,
    respuesta       VARCHAR(1000),
    fecha_respuesta TIMESTAMP,
    CONSTRAINT fk_contactos_comprador FOREIGN KEY (comprador_id)
        REFERENCES compradores (id),
    CONSTRAINT fk_contactos_producto FOREIGN KEY (producto_id)
        REFERENCES productos (id)
);

-- ---------------------------------------------------------------------
-- pedidos: pedido de un comprador a un agricultor
-- (el total no se guarda: se calcula desde detalles_pedido)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pedidos (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado                 VARCHAR(20)  NOT NULL,
    direccion_entrega      VARCHAR(255) NOT NULL,
    fecha_creacion         TIMESTAMP    NOT NULL,
    fecha_estimada_llegada DATE,
    fecha_entrega          TIMESTAMP,
    motivo_cancelacion     VARCHAR(500),
    comprador_id           BIGINT       NOT NULL,
    agricultor_id          BIGINT       NOT NULL,
    CONSTRAINT fk_pedidos_comprador FOREIGN KEY (comprador_id)
        REFERENCES compradores (id),
    CONSTRAINT fk_pedidos_agricultor FOREIGN KEY (agricultor_id)
        REFERENCES agricultores (id),
    CONSTRAINT ck_pedidos_estado CHECK (estado IN (
        'PENDIENTE', 'CONFIRMADO', 'EN_TRANSPORTE', 'ENTREGADO', 'CANCELADO'))
);

-- ---------------------------------------------------------------------
-- detalles_pedido: líneas del pedido (un producto una sola vez por pedido)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS detalles_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT         NOT NULL,
    producto_id     BIGINT         NOT NULL,
    cantidad        INTEGER        NOT NULL,
    precio_unitario NUMERIC(38, 2) NOT NULL,
    CONSTRAINT fk_detalles_pedido_pedido FOREIGN KEY (pedido_id)
        REFERENCES pedidos (id),
    CONSTRAINT fk_detalles_pedido_producto FOREIGN KEY (producto_id)
        REFERENCES productos (id),
    CONSTRAINT uk_detalles_pedido_producto UNIQUE (pedido_id, producto_id)
);

-- ---------------------------------------------------------------------
-- pagos: intentos de pago de un pedido (varios por pedido: reintentos)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pagos (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id              BIGINT         NOT NULL,
    medio_pago             VARCHAR(30)    NOT NULL,
    referencia_transaccion VARCHAR(255)   NOT NULL,
    monto                  NUMERIC(38, 2) NOT NULL,
    estado                 VARCHAR(20)    NOT NULL,
    fecha_pago             TIMESTAMP,
    fecha_liberacion       TIMESTAMP,
    CONSTRAINT fk_pagos_pedido FOREIGN KEY (pedido_id)
        REFERENCES pedidos (id),
    CONSTRAINT uk_pagos_referencia UNIQUE (referencia_transaccion),
    CONSTRAINT ck_pagos_estado CHECK (estado IN (
        'PENDIENTE', 'COMPLETADO', 'RECHAZADO', 'REEMBOLSADO'))
);

-- ---------------------------------------------------------------------
-- transportistas: perfil de transportista (1:1 con usuarios)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS transportistas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipio  VARCHAR(255) NOT NULL,
    usuario_id BIGINT       NOT NULL,
    CONSTRAINT uk_transportistas_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_transportistas_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id)
);

-- ---------------------------------------------------------------------
-- vehiculos: vehículo del transportista (1:1 según el DER)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS vehiculos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_transporte  VARCHAR(255) NOT NULL,
    placa            VARCHAR(10)  NOT NULL,
    capacidad_kg     INTEGER      NOT NULL,
    transportista_id BIGINT       NOT NULL,
    CONSTRAINT uk_vehiculos_placa         UNIQUE (placa),
    CONSTRAINT uk_vehiculos_transportista UNIQUE (transportista_id),
    CONSTRAINT fk_vehiculos_transportista FOREIGN KEY (transportista_id)
        REFERENCES transportistas (id),
    CONSTRAINT ck_vehiculos_capacidad CHECK (capacidad_kg > 0)
);

-- ---------------------------------------------------------------------
-- rutas: ruta de un vehículo en una fecha (un vehículo, varias rutas)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS rutas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha       DATE   NOT NULL,
    vehiculo_id BIGINT NOT NULL,
    CONSTRAINT fk_rutas_vehiculo FOREIGN KEY (vehiculo_id)
        REFERENCES vehiculos (id)
);

-- ---------------------------------------------------------------------
-- asignaciones_transporte: asigna un pedido a una ruta
-- (un pedido se asigna a una sola ruta; una ruta lleva varios pedidos)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS asignaciones_transporte (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT    NOT NULL,
    ruta_id          BIGINT    NOT NULL,
    orden_entrega    INTEGER   NOT NULL,
    fecha_asignacion TIMESTAMP NOT NULL,
    CONSTRAINT uk_asignaciones_pedido UNIQUE (pedido_id),
    CONSTRAINT fk_asignaciones_pedido FOREIGN KEY (pedido_id)
        REFERENCES pedidos (id),
    CONSTRAINT fk_asignaciones_ruta FOREIGN KEY (ruta_id)
        REFERENCES rutas (id),
    CONSTRAINT ck_asignaciones_orden CHECK (orden_entrega > 0)
);

-- ---------------------------------------------------------------------
-- facturas: factura de un pedido (1:1 con pedidos)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS facturas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT         NOT NULL,
    numero          VARCHAR(30)    NOT NULL,
    fecha_emision   TIMESTAMP      NOT NULL,
    valor_impuestos NUMERIC(38, 2) NOT NULL,
    CONSTRAINT uk_facturas_pedido UNIQUE (pedido_id),
    CONSTRAINT uk_facturas_numero UNIQUE (numero),
    CONSTRAINT fk_facturas_pedido FOREIGN KEY (pedido_id)
        REFERENCES pedidos (id)
);

-- ---------------------------------------------------------------------
-- calificaciones: calificación de un pedido (1:1 con pedidos)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS calificaciones (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id  BIGINT        NOT NULL,
    puntuacion INTEGER       NOT NULL,
    comentario VARCHAR(1000),
    fecha      TIMESTAMP     NOT NULL,
    CONSTRAINT uk_calificaciones_pedido UNIQUE (pedido_id),
    CONSTRAINT fk_calificaciones_pedido FOREIGN KEY (pedido_id)
        REFERENCES pedidos (id),
    CONSTRAINT ck_calificaciones_puntuacion CHECK (puntuacion BETWEEN 1 AND 5)
);

-- ---------------------------------------------------------------------
-- inconformidades: reclamos sobre un pedido (varios por pedido)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS inconformidades (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id     BIGINT        NOT NULL,
    descripcion   VARCHAR(1000) NOT NULL,
    evidencia_url VARCHAR(500),
    estado        VARCHAR(20)   NOT NULL,
    resolucion    VARCHAR(1000),
    fecha_reporte TIMESTAMP     NOT NULL,
    CONSTRAINT fk_inconformidades_pedido FOREIGN KEY (pedido_id)
        REFERENCES pedidos (id),
    CONSTRAINT ck_inconformidades_estado CHECK (estado IN (
        'ABIERTA', 'EN_REVISION', 'RESUELTA'))
);

-- ---------------------------------------------------------------------
-- Índices sobre llaves foráneas (mejoran joins y consultas frecuentes)
-- ---------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_productos_agricultor   ON productos (agricultor_id);
CREATE INDEX IF NOT EXISTS idx_productos_categoria    ON productos (categoria);
CREATE INDEX IF NOT EXISTS idx_contactos_comprador    ON contactos (comprador_id);
CREATE INDEX IF NOT EXISTS idx_contactos_producto     ON contactos (producto_id);
CREATE INDEX IF NOT EXISTS idx_pedidos_comprador      ON pedidos (comprador_id);
CREATE INDEX IF NOT EXISTS idx_pedidos_agricultor     ON pedidos (agricultor_id);
CREATE INDEX IF NOT EXISTS idx_pedidos_estado         ON pedidos (estado);
CREATE INDEX IF NOT EXISTS idx_detalles_pedido_pedido ON detalles_pedido (pedido_id);
CREATE INDEX IF NOT EXISTS idx_pagos_pedido           ON pagos (pedido_id);
CREATE INDEX IF NOT EXISTS idx_vehiculos_transportista ON vehiculos (transportista_id);
CREATE INDEX IF NOT EXISTS idx_rutas_vehiculo          ON rutas (vehiculo_id);
CREATE INDEX IF NOT EXISTS idx_asignaciones_ruta       ON asignaciones_transporte (ruta_id);
CREATE INDEX IF NOT EXISTS idx_inconformidades_pedido  ON inconformidades (pedido_id);
CREATE INDEX IF NOT EXISTS idx_inconformidades_estado  ON inconformidades (estado);